const statsElement = document.querySelector('.stats');
const questionText = document.getElementById('question-text');
const questionHelper = document.getElementById('question-helper');
const cardsGrid = document.querySelector('.quiz-grid');
const restartButton = document.getElementById('btn-reiniciar');
const categoryButtons = document.querySelectorAll('.category-card');
const leaderboardList = document.getElementById('leaderboard-list');
const categoryLabel = document.getElementById('category-label');
const progressBar = document.getElementById('progress-bar');

const rankingKey = 'quizlab-ranking-com-nome-v1';

let currentCategory = 'Geografia';
let questions = [...questionBank[currentCategory]];
let currentQuestionIndex = 0;
let score = 0;
let answerLocked = false;

function renderQuestion() {
    if (currentQuestionIndex >= questions.length) {
        showResult();
        return;
    }

    const current = questions[currentQuestionIndex];
    const progress = (currentQuestionIndex / questions.length) * 100;

    statsElement.textContent = `Questão ${currentQuestionIndex + 1} de ${questions.length}`;
    questionText.textContent = current.question;
    questionHelper.textContent = 'Escolha uma alternativa para avançar.';
    categoryLabel.textContent = currentCategory;
    progressBar.style.width = `${progress}%`;

    cardsGrid.innerHTML = '';

    current.answers.forEach((answer, index) => {
        const button = document.createElement('button');
        button.className = 'answer-card';
        button.type = 'button';
        button.textContent = answer;
        button.dataset.index = String(index);
        button.addEventListener('click', handleAnswer);
        cardsGrid.appendChild(button);
    });
}

function handleAnswer(event) {
    if (answerLocked) return;
    answerLocked = true;

    const button = event.currentTarget;
    const selectedIndex = Number(button.dataset.index);
    const current = questions[currentQuestionIndex];
    const buttons = Array.from(cardsGrid.children);

    buttons.forEach((btn) => {
        btn.disabled = true;
        const btnIndex = Number(btn.dataset.index);

        if (btnIndex === current.correctIndex) {
            btn.classList.add('correct');
        }
    });

    if (selectedIndex === current.correctIndex) {
        score += 1;
        button.classList.add('correct');
        questionHelper.textContent = 'Boa! Resposta correta.';
    } else {
        button.classList.add('wrong');
        questionHelper.textContent = 'Quase! A alternativa correta ficou marcada em verde.';
    }

    progressBar.style.width = `${((currentQuestionIndex + 1) / questions.length) * 100}%`;

    setTimeout(() => {
        currentQuestionIndex += 1;
        answerLocked = false;
        renderQuestion();
    }, 900);
}

function showResult() {
    statsElement.textContent = 'Quiz finalizado';
    questionText.textContent = `Resultado em ${currentCategory}`;
    questionHelper.textContent = 'Digite seu nome para salvar sua pontuação no ranking.';
    categoryLabel.textContent = currentCategory;
    progressBar.style.width = '100%';

    cardsGrid.innerHTML = `
        <div class="result-summary">
            <p>Você acertou <strong>${score}</strong> de <strong>${questions.length}</strong> perguntas.</p>
            <p>${getFeedback(score)}</p>

            <div class="save-score-box">
                <label class="save-score-box__label" for="player-name">Nome do jogador</label>
                <input
                    id="player-name"
                    class="player-name-input"
                    type="text"
                    placeholder="Digite seu nome"
                    maxlength="20"
                    autocomplete="off"
                >
                <button id="btn-save-score" class="answer-card action-card" type="button">Salvar pontuação</button>
                <p id="save-message" class="save-message" aria-live="polite"></p>
            </div>

            <button id="btn-reset-final" class="answer-card action-card" type="button">Refazer ${currentCategory}</button>
        </div>
    `;

    const resetFinalButton = document.getElementById('btn-reset-final');
    const saveScoreButton = document.getElementById('btn-save-score');
    const playerNameInput = document.getElementById('player-name');
    const saveMessage = document.getElementById('save-message');

    playerNameInput.focus();
    resetFinalButton.addEventListener('click', resetQuiz);

    saveScoreButton.addEventListener('click', () => {
        const playerName = playerNameInput.value.trim();

        if (playerName.length === 0) {
            saveMessage.textContent = 'Digite um nome antes de salvar.';
            saveMessage.classList.remove('save-message--success');
            saveMessage.classList.add('save-message--error');
            playerNameInput.focus();
            return;
        }

        saveScore(playerName);
        renderLeaderboard();

        saveMessage.textContent = 'Pontuação salva com sucesso!';
        saveMessage.classList.remove('save-message--error');
        saveMessage.classList.add('save-message--success');

        saveScoreButton.disabled = true;
        playerNameInput.disabled = true;
    });

    playerNameInput.addEventListener('keydown', (event) => {
        if (event.key === 'Enter') {
            saveScoreButton.click();
        }
    });
}

function getFeedback(scoreValue) {
    if (scoreValue === questions.length) return 'Perfeito! Você mandou muito bem nessa área.';
    if (scoreValue >= 7) return 'Muito bom! Você tem um ótimo domínio do conteúdo.';
    if (scoreValue >= 4) return 'Bom começo! Revise alguns pontos e tente novamente.';
    return 'Continue treinando. O importante é praticar e melhorar a cada tentativa.';
}

function resetQuiz() {
    currentQuestionIndex = 0;
    score = 0;
    answerLocked = false;
    questions = [...questionBank[currentCategory]];
    renderQuestion();
}

function changeCategory(categoryName) {
    currentCategory = categoryName;

    categoryButtons.forEach((button) => {
        button.classList.toggle('category-card--active', button.dataset.category === categoryName);
    });

    resetQuiz();
}

function getSavedScores() {
    try {
        return JSON.parse(localStorage.getItem(rankingKey)) || [];
    } catch (error) {
        return [];
    }
}

function saveScore(playerName) {
    const scores = getSavedScores();

    scores.push({
        player: playerName,
        score,
        total: questions.length,
        category: currentCategory,
        date: new Date().toLocaleDateString('pt-BR'),
        createdAt: Date.now(),
    });

    scores.sort((a, b) => {
        if (b.score !== a.score) return b.score - a.score;
        return b.createdAt - a.createdAt;
    });

    localStorage.setItem(rankingKey, JSON.stringify(scores.slice(0, 5)));
}

function renderLeaderboard() {
    const scores = getSavedScores();
    leaderboardList.innerHTML = '';

    if (scores.length === 0) {
        const item = document.createElement('li');
        const text = document.createElement('span');
        text.textContent = 'Nenhuma pontuação ainda';
        item.appendChild(text);
        leaderboardList.appendChild(item);
        return;
    }

    scores.forEach((item) => {
        const listItem = document.createElement('li');
        const content = document.createElement('span');
        const detail = document.createElement('small');

        content.textContent = `${item.player} — ${item.score}/${item.total}`;
        detail.textContent = `${item.category} • ${item.date}`;

        content.appendChild(detail);
        listItem.appendChild(content);
        leaderboardList.appendChild(listItem);
    });
}

categoryButtons.forEach((button) => {
    button.addEventListener('click', () => changeCategory(button.dataset.category));
});

restartButton.addEventListener('click', resetQuiz);

renderLeaderboard();
renderQuestion();
